/// 单条最多提取的主题数。
const MAX_TAGS: usize = 3;

/// 从标题提取主题标签（0~3 个，按规则表顺序去重）。
pub fn extract_tags(title: &str) -> Vec<String> {
    let t = title.to_lowercase();
    let mut tags = Vec::new();
    for (topic, keywords) in RULES {
        if keywords.iter().any(|k| t.contains(k)) {
            tags.push((*topic).to_string());
            if tags.len() >= MAX_TAGS {
                break;
            }
        }
    }
    tags
}

/// 为无 tags 的条目补标签；已有 tags 的（如 B 站 tname）保持原样。
pub fn fill_tags(item: &mut HotItem) {
    if !item.tags.is_empty() {
        return;
    }
    item.tags = extract_tags(&item.title);
}

#[cfg(test)]
mod tests {
    use super::*;
    use deskpet_core::TrustLevel;

    #[test]
    fn extracts_ai_and_tech() {
        let tags = extract_tags("DeepSeek 发布新一代大模型，性能对标 GPT");
        assert!(tags.contains(&"AI".to_string()));
    }

    #[test]
    fn extracts_multiple_topics_capped_at_three() {
        let tags = extract_tags("华为发布会推出新手机，搭载自研芯片，评测已出");
        assert!(tags.len() <= 3);
        assert!(tags.contains(&"科技".to_string()) || tags.contains(&"数码".to_string()));
    }

    #[test]
    fn returns_empty_when_no_keyword_matches() {
        let tags = extract_tags("这是一句没有任何领域关键词的普通标题呢");
        assert!(tags.is_empty());
    }

    #[test]
    fn fill_tags_keeps_existing() {
        let mut item = crate::adapter::build_item(
            "bilibili", 1, "某游戏实况", "https://x", 0, TrustLevel::Direct,
        );
        item.tags.push("游戏".to_string());
        fill_tags(&mut item);
        assert_eq!(item.tags, vec!["游戏".to_string()]);
    }

    #[test]
    fn fill_tags_populates_empty() {
        let mut item = crate::adapter::build_item(
            "zhihu", 1, "如何看待央行降息对股市的影响", "https://x", 0, TrustLevel::Direct,
        );
        fill_tags(&mut item);
        assert!(item.tags.contains(&"财经".to_string()));
    }
}
